/** MDXEditor `translation` prop: English by default, Chinese when the app language is 中文. */
export function editorTranslation(key: string, defaultValue: string, interpolations?: Record<string, unknown>): string {
  const text = getLang() === "zh" ? (ZH[key] ?? defaultValue) : defaultValue;
  return text.replace(/\{\{(\w+)\}\}/g, (m, name: string) => (interpolations && name in interpolations ? String(interpolations[name]) : m));
}
